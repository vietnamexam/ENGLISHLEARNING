export function buildSampleGameFromSpec(spec: SampleGameSpec): GameRecord {
  const pool = GAME_QUESTION_BANK[spec.gameType] || [];
  const chosen = pickRandom(pool, spec.questionCount).map((q) => ({
    ...q,
    options: spec.gameType === 'sentence_order' ? shuffleArray(q.options) : [...q.options],
  }));

  return {
    id: spec.id,
    teacherId: 'system-sample',
    title: spec.title,
    gameType: spec.gameType,
    topic: spec.topic,
    difficulty: spec.difficulty,
    questionCount: chosen.length,
    questions: chosen,
    isActive: true,
  };
}

export function buildAllSampleGames(): GameRecord[] {
  return SAMPLE_GAME_SPECS.map(buildSampleGameFromSpec);
}

export function rerollSampleGameById(gameId: string): GameRecord | null {
  const spec = SAMPLE_GAME_SPECS.find((s) => s.id === gameId);
  return spec ? buildSampleGameFromSpec(spec) : null;
}
